function s = makeIssue(code, path, message, hint, severity)
%MAKEISSUE 构造结构化问题项 {code, path, message, hint, severity}。
%   errors / warnings 列表中的每个元素都是本函数生成的结构体，可被 jsonencode。
%   severity 取 'error'（默认）或 'warning'。
if nargin < 5 || isempty(severity)
    severity = 'error';
end
s = struct( ...
    'code', char(code), ...
    'path', char(path), ...
    'message', char(message), ...
    'hint', char(hint), ...
    'severity', char(severity));
end
