function [formats, details] = supportedFormats()
%SUPPORTEDFORMATS 返回 bma.io 支持的文献格式列表。
%   formats = bma.io.supportedFormats()
%       返回扩展名 cellstr（含点号，小写），可直接作为工具/文档的格式清单：
%       {'.pdf','.docx','.txt','.md','.markdown','.html','.htm'}
%   [formats, details] = bma.io.supportedFormats()
%       details 为 struct 数组，字段：extension / format / reader / binary。
formats = {'.pdf', '.docx', '.txt', '.md', '.markdown', '.html', '.htm'};
specs = { ...
    '.pdf', 'pdf', 'extractFileText (Text Analytics Toolbox)', true; ...
    '.docx', 'docx', 'extractFileText (Text Analytics Toolbox)', true; ...
    '.txt', 'txt', 'readText (UTF-8)', false; ...
    '.md', 'markdown', 'readText (UTF-8)', false; ...
    '.markdown', 'markdown', 'readText (UTF-8)', false; ...
    '.html', 'html', 'htmlTree/extractHTMLText (+regex fallback)', false; ...
    '.htm', 'html', 'htmlTree/extractHTMLText (+regex fallback)', false};
details = struct('extension', specs(:, 1)', 'format', specs(:, 2)', ...
    'reader', specs(:, 3)', 'binary', specs(:, 4)');
end
