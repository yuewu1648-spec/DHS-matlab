function mask = excludedMask(text)
%EXCLUDEDMASK 标记文献中“数字不可信”的区间（URL/DOI/引文/图表编号/年份语境等）。
%   mask = bma.io.internal.excludedMask(text)
%   这些区间内的数字一律不参与参数抽取，避免把页码、引用编号、图表编号、
%   年份、序列号误报成模型参数（precision-first）。
%
%   注：MATLAB regexp 不使用 \b 作为词边界（其语义与 PCRE 不同），
%   这里统一用「前导非字母数字字符 + 否定前瞻」表达词边界。
mask = false(1, numel(text));
NB = '(?:^|[^A-Za-z0-9])';       % 前导边界
NA = '(?![A-Za-z0-9])';          % 尾随边界
patterns = { ...
    '(?:https?://|ftp://|www\.)\S+', ...
    '(?:doi:\s*|https?://(?:dx\.)?doi\.org/)?10\.\d{4,9}/\S+', ...
    '[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}', ...
    '\[[^\]]{0,120}\]', ...
    [NB '(?:Fig(?:ure)?|Tab(?:le)?|Eq(?:uation)?|Sec(?:tion)?|Ref(?:erence)?s?|Supp(?:lementary)?|Chapter|Appendix|Scheme|Plate)\.?\s*S?\d+[A-Za-z]?' NA], ...
    [NB '[A-Z][A-Za-z''\-]+(?:\s+et\s+al\.?,?|(?:\s+and\s+[A-Z][A-Za-z''\-]+)?,?)\s*\(?(?:19|20)\d{2}\)?'], ...
    [NB '[pP]{1,2}\.\s*\d+'], ...
    [NB '(?:pages?|Page)\s+\d+'], ...
    [NB 'Vol\.\s*\d+'], ...
    [NB '(?:Received|Accepted|Published|Revised|Available online)' NA '[^\n]{0,40}?(?:19|20)\d{2}'], ...
    [NB '[A-Z]{2,4}_?\d{4,}' NA], ...
    [NB '(?:version|Version|v)\s*\d+(?:\.\d+)+']};
for k = 1:numel(patterns)
    mask = bma.io.internal.markPattern(text, mask, patterns{k});
end
end
