function s = htmlUnescape(s)
%HTMLUNESCAPE 解码常见 HTML 实体（命名实体 + 数字实体）。
if isempty(s)
    return
end
s = char(s);
pairs = { ...
    '&nbsp;', ' '; ...
    '&amp;', '&'; ...
    '&lt;', '<'; ...
    '&gt;', '>'; ...
    '&quot;', '"'; ...
    '&apos;', char(39); ...
    '&#39;', char(39); ...
    '&mdash;', '-'; ...
    '&ndash;', '-'; ...
    '&minus;', '-'; ...
    '&micro;', char(181); ...
    '&times;', 'x'; ...
    '&deg;', char(176)};
for k = 1:size(pairs, 1)
    s = strrep(s, pairs{k, 1}, pairs{k, 2});
end
% 十进制数字实体
[matches, tokens] = regexp(s, '&#(\d+);', 'match', 'tokens');
for k = 1:numel(matches)
    code = str2double(tokens{k}{1});
    if isfinite(code) && code > 0 && code < 65536
        s = strrep(s, matches{k}, char(code));
    end
end
% 十六进制数字实体
[matches, tokens] = regexp(s, '&#[xX]([0-9A-Fa-f]+);', 'match', 'tokens');
for k = 1:numel(matches)
    code = hex2dec(tokens{k}{1});
    if code > 0 && code < 65536
        s = strrep(s, matches{k}, char(code));
    end
end
end
