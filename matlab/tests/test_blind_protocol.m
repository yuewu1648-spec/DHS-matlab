        '模型能给出区分转录抑制与磷酸化的实验预测'}})));
assert(g.question.recorded, 'goal 未记录');

% over_budget 的 2 倍阈值
badRound = struct('summary', ['校验预算阈值：这一轮的总结足够长，用于测试 over_budget 必须满足 ' ...
    'spent >= 2*limit，否则不允许作为停止理由；本轮还会检查 summary 长度、checks 证据与 issue 字段校验。'], ...
    'checks', {{struct('name', 'spec', 'result', 'pass', 'evidence', 'validate ok'), ...
    struct('name', 'structure', 'result', 'pass', 'evidence', 'analyze ok'), ...
    struct('name', 'numerics', 'result', 'pass', 'evidence', 'simulate ok')}}, ...
    'issues', {{struct('category', 'numerics', 'severity', 'P2', ...
        'title', '计算量超出预算', 'detail', '继续细化 PDE 网格的代价过高，需要记录预算。', ...
        'status', 'over_budget', 'reason', ['继续细化网格需要额外大量计算，' ...
        '已明显超出本轮预算，按协议要求记录为 over_budget。'], ...
        'evidence', '已投入 1 s，预算 1 s；预计还要数小时。', ...
        'budget', struct('spent_s', 1, 'limit_s', 1))}});
expectError(@() bma.blind.check(work, runDir, struct('action', 'round', 'round', badRound)), ...
    'issue_invalid', '未达 2 倍的 over_budget 未被拒绝');

