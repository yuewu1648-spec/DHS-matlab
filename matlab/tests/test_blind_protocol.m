% test_blind_protocol.m — BLIND-LIT：摘要封印、逐篇参考文献、自检-冻结-停止、解封对照
%
% 覆盖：
%   1) start 只暴露摘要，绝不落盘/返回主文献正文；参考文献清单与封面；
%   2) ingest 封印（本 run + 新建 run 的工作区级封印）按路径与 SHA-256 生效；
%   3) note 的逐字 quote 校验（转述必须被拒绝）；coverage 完整；
%   4) goal/round 校验；fix_kind=model 必须伴随 spec hash 变化；
%   5) over_budget 必须 spent >= 2*limit；min_rounds/冻结/停止判据；
%   6) freeze + stop 写 blind_summary.md；reveal 后全文可读且含正文标记；
%   7) compare 八维校验并写 model_comparison.md；
%   8) 无 Abstract 标题时拒绝 guess，abstract_path 提供权威摘要后可启动；
%   9) from_primary 只暴露题录；题录-only 参考文献记为 limited，不能假称读完。
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(fullfile(root, 'matlab'));

base = tempname;
mkdir(base);
cleaner = onCleanup(@() rmdir(base, 's')); %#ok<NASGU>
work = fullfile(base, 'work');
bma.util.ensureDir(work);
runDir = fullfile(work, '.bma', 'runs', 'r-smoke');
bma.util.ensureDir(fullfile(runDir, 'models'));

primary = fullfile(work, 'primary.txt');
writeText(primary, [ ...
    'Regulation of hexose uptake in yeast' newline ...
    'Alice Smith and Bob Lee' newline newline ...
    'Abstract' newline ...
    'We investigate how glucose uptake is regulated in yeast during nitrogen starvation. ' ...
    'We ask whether the hexose transporter Hxt7 is controlled by a transcriptional repressor ' ...
    'or by direct phosphorylation. We hypothesize that the kinase Snf1 phosphorylates Hxt7 ' ...
    'and reduces its surface abundance within 30 min.' newline ...
    'Keywords: glucose, Hxt7, Snf1' newline newline ...
    '1. Introduction' newline ...
    'SECRET_PRIMARY_BODY: the full text describes a detailed model with many parameters.' newline ...
    '2. Results' newline 'SECRET_RESULTS too.' newline newline ...
    'References' newline ...
    '[1] Smith A. 2019. Hexose transporter kinetics in yeast. J Biol 12:3-9.' newline ...
    '[2] Lee B. 2020. Snf1 phosphorylation of transporters. Mol Cell 4:100-110.' newline]);

refDir = fullfile(work, 'refs');
bma.util.ensureDir(refDir);
writeText(fullfile(refDir, 'ref1.txt'), [ ...
    'Hexose transporter kinetics in yeast' newline ...
    'Abstract' newline ...
    'We measured glucose uptake in wild-type yeast. The Km for glucose uptake was 12.5 uM ' ...
    'and Vmax was 240 nmol/min/mg protein.' newline ...
    'Results' newline ...
    'Under nitrogen starvation, transporter abundance decreased by 60% within 30 min.' newline]);
writeText(fullfile(refDir, 'ref2.txt'), [ ...
    'Snf1 phosphorylation of transporters' newline ...
    'Abstract' newline ...
    'Snf1 directly phosphorylates the Hxt7 N-terminus at serine 25 in vitro.' newline ...
    'Results' newline ...
    'Phosphorylation reduced surface abundance in a dose-dependent manner.' newline]);

% =====================================================================
% 1) start：只暴露摘要
% =====================================================================
r1 = bma.blind.start(work, runDir, primary, struct( ...
    'references_dir', refDir, 'min_rounds', 2));
assert(r1.references.count == 2, '参考文献清单数量错误');
assert(contains(r1.primary.abstract_text, 'We ask whether'), '摘要缺少问题句');
assert(~contains(r1.primary.abstract_text, 'SECRET'), '摘要泄漏了正文标记');
assert(strcmp(r1.primary.abstract_source, 'section'), '摘要应来自 Abstract 章节');
md = fileread(fullfile(runDir, 'blind', 'primary_abstract.md'));
assert(~contains(md, 'SECRET'), '摘要档案泄漏了正文');
assert(~contains(md, 'SECRET_PRIMARY_BODY'), '摘要档案泄漏了正文（2）');
prot = bma.util.readJson(fullfile(runDir, 'blind', 'protocol.json'));
assert(prot.guard.sealed && prot.guard.ingest_blocked, '协议应处于封印状态');
assert(numel(prot.primary.sha256) == 64, '主文献 SHA-256 缺失');

% =====================================================================
% 2) ingest 封印：本 run + 新 run 都不能绕过
% =====================================================================
expectError(@() bma.io.ingest(primary, runDir), 'sealed', '本 run 的 ingest 未被封印');
runOther = fullfile(work, '.bma', 'runs', 'r-other');
bma.util.ensureDir(runOther);
expectError(@() bma.io.ingest(primary, runOther), 'sealed', '新建 run 绕过了工作区封印');
assert(isfile(fullfile(work, '.bma', 'blind', 'seals.json')), '缺少工作区封印登记表');

% =====================================================================
% 3) note：逐字 quote 校验；coverage
% =====================================================================
note1 = struct('depth', 'full_text', ...
    'claims', {{struct('kind', 'parameter', ...
        'claim', '葡萄糖摄取的 Km 为 12.5 uM，Vmax 为 240 nmol/min/mg', ...
        'quote', 'Km for glucose uptake was 12.5 uM', 'location', 'Abstract'), ...
    struct('kind', 'mechanism', ...
        'claim', '氮饥饿 30 min 内转运体丰度下降 60%', ...
        'quote', 'transporter abundance decreased by 60% within 30 min', ...
        'location', 'Results')}}, ...
    'relevance', struct( ...
        'question_link', '给出 Hxt7 摄取的动力学参数与氮饥饿下的丰度变化，可直接约束模型', ...
        'modeling_use', 'parameter'));
n1 = bma.blind.note(work, runDir, 'R1', note1);
assert(strcmp(n1.status, 'read'), 'R1 应为 read');
assert(n1.verification.quotes_found == 2, 'R1 quote 应全部找到');
assert(n1.coverage.read == 1 && n1.coverage.total == 2, 'R1 后 coverage 应为 1/2');

badNote = note1;
badNote.claims{1}.quote = 'glucose uptake Km 12.5 micromolar';
expectError(@() bma.blind.note(work, runDir, 'R1', badNote), ...
    'quote_not_found', '转述的 quote 未被拒绝');

note2 = struct('depth', 'full_text', ...
    'claims', {{struct('kind', 'mechanism', ...
        'claim', 'Snf1 直接磷酸化 Hxt7 N 端丝氨酸 25', ...
        'quote', 'Snf1 directly phosphorylates the Hxt7 N-terminus at serine 25', ...
        'location', 'Abstract')}}, ...
    'relevance', struct( ...
        'question_link', '直接支持 Snf1 磷酸化 Hxt7 的机制候选，是区分转录抑制与磷酸化假说的关键证据', ...
        'modeling_use', 'mechanism'));
n2 = bma.blind.note(work, runDir, 'R2', note2);
assert(n2.coverage.complete, '两篇读完后 coverage 应 complete');
assert(isempty(n2.remaining_ids), '不应还有剩余文献');

% =====================================================================
% 4) goal + round 校验
% =====================================================================
st0 = bma.blind.check(work, runDir, struct('action', 'status'));
assert(~st0.can_stop, '未记录 goal 时不应允许 stop');

