% =====================================================================
function writeText(path, txt)
fid = fopen(path, 'w', 'n', 'UTF-8');
assert(fid > 0, '无法写测试文件：%s', path);
fwrite(fid, txt, 'char');
fclose(fid);
end

function expectError(fn, needle, msg)
threw = false;
try
    fn();
catch err
    threw = true;
    assert(contains(lower(err.identifier), lower(needle)) || ...
        contains(lower(err.message), lower(needle)), ...
        '%s：错误码/消息不含 "%s"（实际 %s: %s）', msg, needle, ...
        err.identifier, err.message);
end
assert(threw, '%s：没有抛出错误', msg);
end
