% test_model_selection_partial.m — ISSUE-004 candidate status + partial results
root = bma.util.projectRoot();
work = fullfile(root, '.bma', 'test_tmp', bma.util.newId('model_selection'));
bma.util.ensureDir(work);
cands = {struct('name', 'fast_a', 'aicc', -10, 'k', 2, 'n', 100), ...
    struct('name', 'fast_b', 'aicc', 5, 'k', 3, 'n', 100), ...
    struct('name', 'bad_missing', 'spec_path', fullfile(work, 'missing.json'))};
r = bma.validate.modelSelection(cands, struct('work_dir', work, ...
    'run_dir', work, 'candidate_seconds', 5));
assert(isfield(r, 'candidate_status') && numel(r.candidate_status) == 3, ...
    'candidate_status 缺失');
assert(any(strcmp({r.candidate_status.status}, 'failed')), '失败候选未标记 failed');
assert(isfield(r, 'partial_path') && isfile(fullfile(work, r.partial_path)), ...
    'partial 结果未落盘');
assert(strcmp(r.best, 'fast_a'), 'best 选择错误：%s', r.best);
fprintf('[PASS] model_selection partial: %d/%d done, best=%s\n', ...
    sum(strcmp({r.candidate_status.status}, 'ok')), numel(cands), r.best);
fprintf('[test_model_selection_partial] 全部通过\n');
