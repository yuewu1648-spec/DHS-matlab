% test_io_sectionize.m — 验证 bma.io.sectionize 的标题识别、覆盖率与边界情况。
% 由 matlab/tests/run_all_tests.m 或 RPC test.run 调用，失败即抛异常。

fprintf('  [test_io_sectionize] start\n');

% ---- 1) 典型生物学论文结构（含前置标题/作者、编号小节、References） ----
sampleLines = { ...
    'Kinetic Characterization of Engineered Enzyme Variants', ...
    'John Smith, Jane Doe, Wei Zhang', ...
    'Department of Biochemistry, Example University', ...
    '', ...
    'Abstract', ...
    ['We report a systematic steady-state kinetic analysis of engineered enzyme variants. ' ...
     'The Michaelis constant Km = 12.5 uM and turnover number kcat = 3.4 s-1 were determined. ' ...
     'The variants were expressed in Escherichia coli and purified by affinity chromatography.'], ...
    '', ...
    '1. Introduction', ...
    ['Enzyme kinetics describes how reaction rates depend on substrate concentration. ' ...
     'The Michaelis-Menten model remains the standard description of saturating enzymes. ' ...
     'Engineered variants are widely used in biocatalysis and metabolic engineering.'], ...
    '', ...
    '2. Materials and Methods', ...
    '2.1 Reagents', ...
    ['All reagents were purchased from commercial suppliers and used without further purification. ' ...
     'Buffer components were of analytical grade and solutions were prepared freshly each day.'], ...
    '', ...
    '2.2 Enzyme assays', ...
    ['Initial velocities were measured at 37 C using a continuous spectrophotometric assay. ' ...
     'The substrate concentration ranged from 1 to 500 uM in assay buffer at pH 7.4.'], ...
    '', ...
    '3. Results', ...
    ['All variants followed Michaelis-Menten kinetics with substrate saturation. ' ...
     'The best variant showed a twofold increase in catalytic efficiency compared with wild type.'], ...
    '', ...
    '4. Discussion', ...
    ['The observed improvements are consistent with increased transition-state stabilization. ' ...
     'Further engineering could target substrate binding and product release steps.'], ...
    '', ...
    'References', ...
    '1. Smith J, Doe J. Engineered enzymes for biocatalysis. J Biol Chem. 2019; 294(4): 1234-1250.', ...
    '2. Zhang W, et al. Kinetic analysis of mutant enzymes. Biochemistry. 2018; 57(12): 3456-3468.'};
sample = strjoin(sampleLines, char(10));
sample = bma.io.internal.normalizeText(sample);

secs = bma.io.sectionize(sample);
assertTrue(isstruct(secs) && ~isempty(secs), 'sectionize 应返回非空 struct 数组');
requiredFields = {'id', 'heading', 'level', 'char_start', 'char_end', 'text', 'kind'};
for f = 1:numel(requiredFields)
    assertTrue(isfield(secs, requiredFields{f}), ...
        sprintf('缺少字段 %s', requiredFields{f}));
end
for k = 1:numel(secs)
    assertTrue(~isempty(secs(k).id), 'section id 不应为空');
    assertTrue(numel(secs(k).text) > 0, sprintf('section %d text 不应为空', k));
    assertTrue(secs(k).char_start >= 1 && secs(k).char_end <= numel(sample), ...
        sprintf('section %d 字符区间越界', k));
end

% ---- 2) 顺序与覆盖率 ----
starts = [secs.char_start];
assertTrue(all(diff(starts) > 0), 'section char_start 必须严格递增');
covered = false(1, numel(sample));
for k = 1:numel(secs)
    covered(secs(k).char_start:secs(k).char_end) = true;
end
coverage = mean(covered);
assertTrue(coverage > 0.95, sprintf('章节覆盖率 %.2f%% 应 > 95%%', coverage * 100));

% ---- 3) 关键章节被识别 ----
headings = lower({secs.heading});
kinds = {secs.kind};
assertTrue(any(contains(headings, 'abstract')), '应识别 Abstract');
assertTrue(any(contains(headings, 'introduction')), '应识别 Introduction');
assertTrue(any(contains(headings, 'materials and methods')), '应识别 Materials and Methods');
assertTrue(any(contains(headings, 'reagents')), '应识别编号小节 2.1 Reagents');
assertTrue(any(contains(headings, 'results')), '应识别 Results');
assertTrue(any(contains(headings, 'discussion')), '应识别 Discussion');
assertTrue(any(contains(headings, 'references')), '应识别 References');
assertTrue(any(strcmp(kinds, 'references')), 'References kind 应为 references');
assertTrue(any(strcmp(kinds, 'methods')), '应存在 kind=methods 章节');
assertTrue(any(strcmp(kinds, 'results')), '应存在 kind=results 章节');
assertTrue(any(strcmp(kinds, 'front_matter')), '标题/作者区应为 front_matter 章节');

% 编号小节层级
lvl = secs(strcmp({secs.heading}, '2.1 Reagents'));
assertTrue(numel(lvl) == 1, '2.1 Reagents 应只出现一次');
assertTrue(lvl(1).level >= 2, '2.1 Reagents 层级应 >= 2');

% ---- 4) 正文行不被误判为标题 ----
assertTrue(~any(contains(headings, 'ml of buffer')), '正文行不应被识别为标题');
assertTrue(~any(contains(headings, 'were purchased')), '正文行不应被识别为标题');

% ---- 5) 无标题文本 -> 单章节，覆盖全文 ----
plain = 'This is a single paragraph without any section heading. It contains numbers 1, 2, 3.';
psec = bma.io.sectionize(plain);
assertTrue(numel(psec) == 1, '无标题文本应返回单章节');
assertTrue(psec(1).char_start == 1 && psec(1).char_end == numel(plain), ...
    '单章节应覆盖全文');

% ---- 6) 空文本 -> 空 struct 数组 ----
esec = bma.io.sectionize('');
assertTrue(isstruct(esec) && isempty(esec), '空文本应返回空 struct 数组');
assertTrue(isfield(esec, 'char_start'), '空 struct 数组应保留字段');

% ---- 7) Markdown 标题 ----
md = sprintf('# Paper Title\n\n## Abstract\n\nSome abstract text here.\n\n## Results\n\nResult text here.\n');
msec = bma.io.sectionize(md);
assertTrue(numel(msec) >= 3, 'Markdown 标题应至少识别 3 节');
assertTrue(any(contains(lower({msec.heading}), 'abstract')), 'Markdown Abstract 应被识别');
assertTrue(msec(1).level == 1 && msec(2).level == 2, 'Markdown 层级应按 # 数量');

% ---- 8) 幂等：同一文本两次 sectionize 结果一致 ----
secs2 = bma.io.sectionize(sample);
assertTrue(numel(secs2) == numel(secs), 'sectionize 应幂等');
assertTrue(isequal([secs2.char_start], [secs.char_start]), 'sectionize 位置应幂等');

fprintf('  [test_io_sectionize] PASS (%d sections, coverage %.1f%%)\n', ...
    numel(secs), coverage * 100);

% ---------------------------------------------------------------------------
function assertTrue(cond, msg)
if ~cond
    error('test_io_sectionize:fail', '%s', msg);
end
end
